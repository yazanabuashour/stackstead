use std::{
    fs::OpenOptions,
    io,
    path::{Path, PathBuf},
};

use std::io::Read as _;

use anyhow::Context as _;
use same_file::Handle;

use crate::{compose, git, manifest::StacksteadManifest, paths};

fn output_paths(manifest: &StacksteadManifest) -> [PathBuf; 4] {
    [
        manifest.env_file.clone(),
        manifest.agent_context.clone(),
        manifest.pointer_file.clone(),
        manifest.worktree.join(compose::OWNERSHIP_OVERRIDE),
    ]
}

fn handle(path: &Path) -> anyhow::Result<Option<Handle>> {
    let inspected = std::fs::metadata(path).and_then(|metadata| {
        if !metadata.is_file() && !metadata.is_dir() {
            return Err(io::Error::new(
                io::ErrorKind::InvalidData,
                "expected a regular file or directory",
            ));
        }
        Handle::from_path(path)
    });
    match inspected {
        Ok(handle) => Ok(Some(handle)),
        Err(error) if error.kind() == io::ErrorKind::NotFound => Ok(None),
        Err(error) => {
            Err(error).with_context(|| format!("cannot inspect generated path {}", path.display()))
        }
    }
}

fn check_aliases(manifest: &StacksteadManifest) -> anyhow::Result<()> {
    let outputs = output_paths(manifest);
    let inputs = manifest
        .compose_files
        .iter()
        .cloned()
        .chain([
            manifest.worktree.join("stackstead.yaml"),
            manifest.worktree.join(".git"),
        ])
        .collect::<Vec<_>>();
    for (index, output) in outputs.iter().enumerate() {
        for other in outputs.iter().skip(index.saturating_add(1)).chain(&inputs) {
            for (leaf, path) in [(output, other), (other, output)] {
                if let Some(leaf_handle) = handle(leaf)? {
                    for ancestor in path
                        .ancestors()
                        .take_while(|path| path.starts_with(&manifest.worktree))
                    {
                        if handle(ancestor)?.is_some_and(|other_handle| other_handle == leaf_handle)
                        {
                            anyhow::bail!(
                                "generated output {} aliases or overlaps {} on this filesystem",
                                output.display(),
                                other.display()
                            );
                        }
                    }
                }
            }
        }
    }
    Ok(())
}

pub(super) fn validate_output_aliases(manifest: &StacksteadManifest) -> anyhow::Result<()> {
    let mut probes = Vec::new();
    let checked = (|| {
        check_aliases(manifest)?;
        for path in output_paths(manifest) {
            if handle(&path)?.is_some() {
                continue;
            }
            let parent = path
                .parent()
                .ok_or_else(|| anyhow::anyhow!("generated output has no parent"))?;
            std::fs::create_dir_all(parent)?;
            let mut options = OpenOptions::new();
            options.read(true).write(true).create_new(true);
            #[cfg(unix)]
            {
                use std::os::unix::fs::OpenOptionsExt as _;
                options.mode(0o600);
            }
            let file = options.open(&path)?;
            probes.push((path, Handle::from_file(file)?));
        }
        check_aliases(manifest)
    })();
    let mut failures = Vec::new();
    for (path, original) in probes {
        let cleanup = (|| {
            if handle(&path)?.is_none_or(|current| current != original) {
                anyhow::bail!(
                    "generated path probe changed at {}; refusing cleanup",
                    path.display()
                );
            }
            std::fs::remove_file(&path)?;
            Ok::<(), anyhow::Error>(())
        })();
        if let Err(error) = cleanup {
            failures.push(error.to_string());
        }
    }
    let cleaned = if failures.is_empty() {
        Ok(())
    } else {
        Err(anyhow::anyhow!("{}", failures.join("; ")))
    };
    match (checked, cleaned) {
        (Ok(()), Ok(())) => Ok(()),
        (Err(error), Ok(())) | (Ok(()), Err(error)) => Err(error),
        (Err(error), Err(cleanup)) => Err(anyhow::anyhow!(
            "{error}; generated path probe cleanup failed: {cleanup}"
        )),
    }
}

fn custom_outputs(manifest: &StacksteadManifest) -> impl Iterator<Item = (&Path, String)> {
    [
        (
            manifest.env_file.as_path(),
            format!(
                "# Generated by Stackstead. Do not edit by hand.\n# Stackstead: {}\n",
                manifest.stackstead_id
            ),
        ),
        (
            manifest.agent_context.as_path(),
            format!("# Stackstead: {}\n", manifest.stackstead_id),
        ),
    ]
    .into_iter()
    .filter(|(path, _)| !path.starts_with(manifest.worktree.join(".stackstead")))
}

fn owned_custom_outputs(manifest: &StacksteadManifest) -> anyhow::Result<Vec<(&Path, Handle)>> {
    let mut owned = Vec::new();
    let custom = custom_outputs(manifest).collect::<Vec<_>>();
    let declared = git::config_at_revision(&manifest.repo_root, &manifest.base)?;
    if paths::safe_generated_path(&manifest.worktree, &declared.env.file)? != manifest.env_file
        || paths::safe_generated_path(&manifest.worktree, &declared.agent.context_file)?
            != manifest.agent_context
    {
        anyhow::bail!(
            "cannot prove generated output ownership: paths differ from the pinned source declaration"
        );
    }
    let unpublished = manifest.status.source == crate::manifest::ComponentStatus::Created
        && paths::is_proven_absent(&manifest.pointer_file);
    for (path, header) in custom {
        let relative = path.strip_prefix(&manifest.worktree)?;
        paths::safe_generated_path(&manifest.worktree, relative)?;
        let tracked = git::is_tracked(&manifest.worktree, relative)?;
        if tracked && unpublished {
            continue;
        }
        let Some(original) = handle(path)? else {
            continue;
        };
        let mut file = original.as_file();
        let mut prefix = vec![0; header.len()];
        file.read_exact(&mut prefix).with_context(|| {
            format!(
                "cannot prove generated output ownership at {}",
                path.display()
            )
        })?;
        if tracked || prefix.as_slice() != header.as_bytes() {
            anyhow::bail!(
                "cannot prove generated output ownership at {}; refusing to remove source",
                path.display()
            );
        }
        owned.push((path, original));
    }
    Ok(owned)
}

pub(super) fn ensure_source_clean(manifest: &StacksteadManifest) -> anyhow::Result<()> {
    let owned = owned_custom_outputs(manifest)?;
    let generated = owned
        .iter()
        .map(|(path, _)| path.strip_prefix(&manifest.worktree))
        .collect::<Result<Vec<_>, _>>()?;
    git::ensure_worktree_clean(&manifest.worktree, &generated)
}

pub(super) fn remove_custom_outputs(manifest: &StacksteadManifest) -> anyhow::Result<()> {
    for (path, original) in owned_custom_outputs(manifest)? {
        if handle(path)?.is_none_or(|current| current != original) {
            anyhow::bail!(
                "generated output changed at {}; refusing cleanup",
                path.display()
            );
        }
        std::fs::remove_file(path)?;
    }
    Ok(())
}

pub(super) fn custom_outputs_removed(manifest: &StacksteadManifest) -> bool {
    custom_outputs(manifest).all(|(path, _)| paths::is_proven_absent(path))
}
